import { feature, nix } from "@adrifer/winix";
import { wsl } from "../system/wsl.ts";

/**
 * One alias table for both shells: zsh (Linux, WSL, macOS) and PowerShell
 * (Windows). A plain string is the same command in both. Otherwise `zsh` is
 * the alias text and `pwsh` a PowerShell function body (arguments in $args);
 * leave a shell out to skip the alias there.
 */
type Alias = string | { zsh?: string; pwsh?: string };

// eza reads the paths to list from stdin when that is not a terminal (scripts,
// pipes), so list the current folder when no path is given.
const pwshLs = `$paths = @($args | Where-Object { -not "$_".StartsWith('-') })
& eza -lh --group-directories-first --icons=auto @args @(if (-not $paths.Count) { '.' })`;

// Like zsh's zd: no argument goes home, an existing path is a normal cd
// (cd -, drives, ~), anything else is a zoxide jump.
const pwshCd = `if ($args.Count -eq 0) { Set-Location -LiteralPath $HOME; return }
try {
    Set-Location @args -ErrorAction Stop
    return
} catch [System.Management.Automation.ItemNotFoundException], [System.Management.Automation.ParameterBindingException] {
    # Not a path (or several keywords): ask zoxide.
}
$before = $PWD.ProviderPath
z @args
if ($PWD.ProviderPath -ne $before) { Write-Host "$([char]::ConvertFromUtf32(0xF17A9)) $($PWD.ProviderPath)" }`;

const aliasTable = (darwin: boolean): Record<string, Alias> => ({
  // Listing
  ls: { zsh: "eza -lh --group-directories-first --icons=auto", pwsh: pwshLs },
  lsa: { zsh: "ls -a", pwsh: "ls -a @args" },
  lt: { zsh: "eza --tree --level=2 --long --icons --git" },
  lt3: { zsh: "lt --level=3" },
  lt4: { zsh: "lt --level=4" },
  lt5: { zsh: "lt --level=5" },
  lta: { zsh: "lt -a" },
  ff: { zsh: "fzf --preview 'bat --style=numbers --color=always {}'" },
  grep: { zsh: "grep --color=auto" },
  // Navigation
  cd: { zsh: "zd", pwsh: pwshCd },
  "..": { zsh: "cd ..", pwsh: "Set-Location .." },
  "...": { zsh: "cd ../..", pwsh: "Set-Location ../.." },
  // Tools
  g: "lazygit",
  lg: "lazygit",
  h: { zsh: "herdr" },
  n: "nvim",
  ci: "code-insiders",
  code: { pwsh: "& code-insiders @args" },
  ts: { zsh: "trackseries" },
  // GitHub Copilot CLI
  co: { zsh: 'copilot --add-dir "$PWD" --yolo', pwsh: "& copilot --add-dir $PWD.ProviderPath --yolo @args" },
  coc: "co --continue",
  cor: "co --resume",
  cou: "copilot update",
  cco: { zsh: "(source ~/custom.env && co)" },
  // Winix: i applies this machine's config, u updates its locks. Linux/WSL and
  // Windows use the `winix` command (pinned Winix, remembered host); macOS has
  // no standalone Winix yet, so it uses npm. Windows has no Nix: u refreshes
  // the Windows lock.
  i: {
    zsh: darwin ? "cd ~/dotfiles/winix && npm install && npx @adrifer/winix switch --host macbook-pro" : "winix switch",
    pwsh: "& winix switch @args",
  },
  u: {
    zsh: darwin ? "cd ~/dotfiles/winix && npm install && npx @adrifer/winix update" : "winix update",
    pwsh: "& winix update --windows @args",
  },
  gc: { zsh: darwin ? "nix-collect-garbage -d" : "sudo nix-collect-garbage -d" },
  ...(darwin && {
    // On Linux/WSL a `winix` alias would hide the winix command.
    winix: { zsh: "npx @adrifer/winix" },
    "foundry-dev": { zsh: "sudo CHOKIDAR_USEPOLLING=true CHOKIDAR_INTERVAL=1000 pnpm dev" },
  }),
});

const zshAliases = (table: Record<string, Alias>) =>
  Object.fromEntries(Object.entries(table).flatMap(([name, alias]) => {
    const command = typeof alias === "string" ? alias : alias.zsh;
    return command ? [[name, command]] : [];
  }));

const powershellAliases = (table: Record<string, Alias>) => {
  const functions = Object.entries(table).flatMap(([name, alias]) => {
    const body = typeof alias === "string" ? `& ${alias} @args` : alias.pwsh;
    return body ? [[name, body] as const] : [];
  });
  return [
    "# Generated by Winix from winix/features/cli/shell.ts; edit the aliases there.",
    "# Built-in aliases (ls, cd, ...) win over functions, so remove them first.",
    `foreach ($name in @(${functions.map(([name]) => `'${name}'`).join(", ")})) {`,
    // Not Test-Path: "alias:.." is the alias drive's parent, not an alias named "..".
    "    if (Get-Alias -Name $name -ErrorAction SilentlyContinue) { Remove-Item -LiteralPath \"alias:$name\" -Force }",
    "}",
    ...functions.map(([name, body]) => `function ${name} {\n${body.split("\n").map((line) => `    ${line}`).join("\n")}\n}`),
    "",
  ].join("\n");
};

/** zsh on Linux/WSL/macOS and PowerShell 7 on Windows, with the same aliases. */
export const shell = feature("shell", ({ home, nixos, windows, platforms }) => {
  const aliases = aliasTable(platforms.darwin.isActive);

  // Windows: PowerShell 7 with the shared profile (starship, zoxide, Windows-only
  // helpers), which loads the generated aliases file.
  windows.package("Microsoft.PowerShell");
  const icons = windows.powershell.module("Terminal-Icons");
  const aliasesFile = windows.file.text(
    windows.knownFolder.userProfile(".config/powershell/aliases.ps1"),
    powershellAliases(aliases),
  );
  windows.powershell.profile("../windows/powershell/Microsoft.PowerShell_profile.ps1", {
    dependsOn: [icons, aliasesFile],
  });
  // The directory that holds this dotfiles checkout; the profile's `repos` goes there.
  windows.env.set("WINIX_REPOS", windows.configPath("../.."));

  const initParts = [
    nix.script(`
           export  ZVM_VI_INSERT_ESCAPE_BINDKEY=jj

           y() {
            local tmp cwd
            tmp="$(mktemp -t yazi-cwd.XXXXXX)"
            yazi "$@" --cwd-file="$tmp"
            if cwd="$(command cat -- "$tmp")" && [[ -n "$cwd" && "$cwd" != "$PWD" ]]; then
              builtin cd -- "$cwd"
            fi
            rm -f -- "$tmp"
          }

          mkcd() {
            if [ $# -ne 1 ]; then
              echo "usage: mkcd <directory>" >&2
              return 2
            fi

            mkdir -p -- "$1" && builtin cd -- "$1"
          }

          zd() {
            if [ $# -eq 0 ]; then
              builtin cd ~ && return
            elif [ -d "$1" ]; then
              builtin cd "$1"
            else
             z "$@" && printf "\\U000F17A9 " && pwd || echo "Error: Directory not found"
           fi
         }

          if (( $+commands[trackseries] )); then
            completion_script="$(trackseries completion zsh 2>/dev/null)" &&
              eval "$completion_script"
            unset completion_script
          fi
        `),
  ];

  if (wsl.isActive) {
    initParts.push(
      nix.script(`
           export BROWSER=wsl-open

           keep_current_path() {
            printf "\\e]9;9;%s\\e\\\\" "$(/bin/wslpath -w "$PWD")"
           }
           precmd_functions+=(keep_current_path)
        `),
    );
  }

  if (platforms.nixos.isActive) {
    nixos.program("zsh", {
      shellInit: nix.script(`
        # Herdr can inherit Home Manager's sourced flags without the variables
        # they guard. Reset only that inconsistent state so ~/.zshenv reloads
        # the active generation's canonical hm-session-vars.sh.
        # Remove once Herdr no longer preserves partial environment snapshots.
        if [[ -n "''\${__HM_SESS_VARS_SOURCED-}" && -z "''\${NPM_CONFIG_PREFIX-}" ]]; then
          unset __HM_SESS_VARS_SOURCED __HM_ZSH_SESS_VARS_SOURCED
        fi
      `),
    });
  }

  home.program("zsh", {
    autosuggestion: {
      enable: true,
    },
    enableCompletion: true,
    syntaxHighlighting: {
      enable: true,
    },
    plugins: [
      {
        name: "zsh-vi-mode",
        src: nix.pkg("zsh-vi-mode"),
        file: "share/zsh-vi-mode/zsh-vi-mode.plugin.zsh",
      },
    ],
    shellAliases: zshAliases(aliases),
    initContent:
      initParts.length === 1 ? initParts[0] : nix.concat(...initParts),
  });
});
